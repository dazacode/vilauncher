"""
Builds the screenshot backgrounds in public/gta6/shots from Rockstar's official screenshot pack
(rockstargames.com/VI/media, GTAVI_Screenshots.zip), and the list of them in src/lib/backdrop-shots.ts.

  python3 compose-screenshots.py <unzipped pack> ../../public/gta6/shots ../../src/lib/backdrop-shots.ts

Each screenshot goes through the same steps as the artwork (compose-backdrops.py): 1440 px high, more sky above,
a soft extension on the left. Where its subject stands is estimated from where the picture's detail is, so the
page can keep it right of the title column; set an anchor by hand in the generated list if one sits badly.
"""
import importlib.util, os, re, sys
from PIL import ImageFilter

spec = importlib.util.spec_from_file_location("art", os.path.join(os.path.dirname(os.path.abspath(__file__)), "compose-backdrops.py"))
art = importlib.util.module_from_spec(spec)
spec.loader.exec_module(art)

# The pack's folders, in the order the picker lists them: people, then places.
ORDER = [
    "Jason_and_Lucia", "Jason_Duval", "Lucia_Caminos", "Boobie_Ike", "Brian_Heder", "Cal_Hampton", "DreQuan_Priest",
    "Raul_Bautista", "Real_Dimez", "Vice_City", "Leonida_Keys", "Grassrivers", "Port_Gellhorn", "Ambrosia",
    "Mount_Kalaga_National_Park",
]


def subject_x(im):
    """How far across the picture its detail is centred (0-1), kept between 0.3 and 0.75."""
    e = im.convert("L").resize((320, 180)).filter(ImageFilter.FIND_EDGES)
    px = e.load()
    cols = [sum(px[x, y] for y in range(18, 162)) for x in range(2, 318)]
    total = sum(cols) or 1
    x = (sum(i * c for i, c in enumerate(cols)) / total + 2) / 320
    return min(0.75, max(0.3, x))


def main(src, out, listing):
    os.makedirs(os.path.join(out, "thumbs"), exist_ok=True)
    found = []
    for root, _, files in os.walk(src):
        for f in files:
            m = re.fullmatch(r"(.+)_(\d+)\.jpg", f)
            if m and m.group(1) in ORDER:
                found.append((ORDER.index(m.group(1)), int(m.group(2)), m.group(1), m.group(2), os.path.join(root, f)))
    found.sort()
    lines = []
    for _, _, group, number, path in found:
        slug = (group + "-" + number).lower().replace("_", "-")
        im = art.Image.open(path).convert("RGB")
        anchor = round(0.2 + 0.8 * subject_x(im), 3)
        art.build(im, out, slug)
        name = group.replace("_", " ")
        lines.append(f'  shot("{slug}", "{name} {number}", "{name}", {anchor}), // i18n-ignore')
        print(slug, anchor)
    with open(listing, "w") as f:
        f.write("// Generated by assets/gta6-src/compose-screenshots.py from Rockstar's screenshot pack: rerun it rather than editing.\n")
        f.write('import type { Backdrop } from "./backdrops"\n\n')
        f.write("const shot = (id: string, name: string, group: string, anchor: number): Backdrop => ({\n")
        f.write("  id,\n  name,\n  group,\n  src: `/gta6/shots/${id}.jpg`,\n  thumb: `/gta6/shots/thumbs/${id}.jpg`,\n")
        f.write("  aspect: 3200 / 1641,\n  anchor,\n  target: 0.72,\n  ty: 0.3,\n})\n\n")
        f.write("/** Rockstar's GTA VI screenshots, by who or where they show. */\n")
        f.write("export const SHOTS: Backdrop[] = [\n" + "\n".join(lines) + "\n]\n")
    print(len(lines), "screenshots")


if __name__ == "__main__":
    main(*sys.argv[1:4])
